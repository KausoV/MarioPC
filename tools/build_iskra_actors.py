"""Compile the supplied Canvas character art and the forest bestiary into a portable PNG atlas."""
from pathlib import Path
import argparse
import base64
import io
from playwright.sync_api import sync_playwright
from PIL import Image

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--chrome", help="Path to an installed Chromium binary")
args = parser.parse_args()
source = (root / "tools/iskra_reference_actors.js").read_text(encoding="utf-8-sig")
art = (root / "tools/iskra_actor_atlas.js").read_text(encoding="utf-8")
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True, executable_path=args.chrome)
    page = browser.new_page()
    # Install only the isolated drawing functions into an empty local document.
    encoded, anchors = page.evaluate("() => {" + source + "\n" + art + "\nreturn [bakeAtlas(),flameAnchors];}")
    assert len(anchors) == 11*8 and all(0 <= x < 96 and 0 <= y < 96 for x,y in anchors)
    browser.close()
png = base64.b64decode(encoded)
image = Image.open(io.BytesIO(png)).convert("RGBA")
# PNG filters before embedding keep generated sources small and fully offline.
buffer = io.BytesIO()
image.save(buffer, format="PNG", compress_level=9)
packed = buffer.getvalue()
target = root / "generated/iskra_actor_atlas.h"
with target.open("w", encoding="ascii", newline="\n") as output:
    output.write("// Generated by tools/build_iskra_actors.py\n#pragma once\nnamespace iskra::art {\n")
    output.write("inline constexpr unsigned char atlas[] = {\n")
    for offset in range(0, len(packed), 32):
        output.write(",".join(map(str, packed[offset:offset+32])) + ",\n")
    output.write("};\ninline constexpr unsigned char flameCenters[11][8][2] = {\n")
    for row in range(11):
        points = anchors[row*8:row*8+8]
        output.write("{" + ",".join("{%d,%d}" % tuple(point) for point in points) + "},\n")
    output.write("};\ninline constexpr unsigned char silhouetteBounds[48][8][4] = {\n")
    for row in range(image.height//96):
        boxes = []
        for n in range(8):
            pose=image.crop((96*n,96*row,96*n+96,96*row+96))
            bounds=pose.getchannel("A").point(lambda a: 255 if a>=180 else 0).getbbox()
            assert bounds
            if row < 11:
                assert min(bounds[:2]) > 0 and max(bounds[2:]) < 96, (row,n,bounds)
            boxes.append("{%d,%d,%d,%d}" % bounds)
        output.write("{"+",".join(boxes)+"},\n")
    output.write("};\n}\n")
preview = root / "build/iskra-actor-preview.png"
# A representative sample from each row at its original frame resolution.
preview_sheet = Image.new("RGB", (8*96, ((image.height//96+7)//8)*96), "#343349")
for row in range(image.height//96):
    sprite = image.crop((96, row*96, 192, (row+1)*96))
    preview_sheet.paste(sprite, (row%8*96, row//8*96), sprite)
preview_sheet.save(preview)
print(f"{image.width} x {image.height}, {len(packed)} bytes embedded, preview {preview}")
