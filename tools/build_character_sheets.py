#!/usr/bin/env python3
"""Prepare the supplied Mario animation sheets as embedded 64 x 128 atlases.

Reproducible with Python 3 and Pillow; requires no runtime image decoder.
Original sheets are copied byte-for-byte into assets/character-sheets.
Only presentation assets are generated; simulation and input are untouched.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import struct
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as PILLOW_VERSION


WIDTH = 64
HEIGHT = 128
BASELINE = 127  # exclusive: the last possible opaque row is 126
FRAME_COUNT = 43
VARIANTS = ("big", "small", "crouch", "growth")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_sheet(path: Path, columns: int, rows: int, retained: int) -> dict:
    with Image.open(path) as original:
        image = original.convert("RGBA")
    expected = (columns * 256, rows * 256)
    if image.size != expected:
        raise ValueError(f"{path.name}: expected {expected}, found {image.size}")
    frames = []
    empty = []
    for index in range(columns * rows):
        column, row = index % columns, index // columns
        cell = image.crop((column * 256, row * 256,
                           (column + 1) * 256, (row + 1) * 256))
        bounds = cell.getchannel("A").getbbox()
        if index >= retained:
            if bounds is not None:
                raise ValueError(f"{path.name}: expected trailing cell {index} to be empty")
            empty.append(index)
            continue
        if bounds is None:
            raise ValueError(f"{path.name}: retained cell {index} is empty")
        frames.append({"source_index": index, "bounds": bounds,
                       "image": cell.crop(bounds)})
    max_width = max(frame["image"].width for frame in frames)
    max_height = max(frame["image"].height for frame in frames)
    big = min(60 / max_width, 122 / max_height)
    small = min(60 / max_width, 62 / max_height)
    return {"path": path, "size": image.size, "columns": columns, "rows": rows,
            "frames": frames, "empty": empty,
            "maximum_bounds_size": (max_width, max_height),
            "scales": (big, small, big * 0.75, big * 0.85)}


def prepare_frame(frame: dict, scale: float) -> Image.Image:
    crop = frame["image"]
    target = (max(1, round(crop.width * scale)),
              max(1, round(crop.height * scale)))
    # Filter premultiplied color to keep green RGB in alpha-zero source pixels
    # from leaking into the silhouette. No color keying is used.
    resized = crop.convert("RGBa").resize(target, Image.Resampling.LANCZOS).convert("RGBA")
    bounds = resized.getchannel("A").getbbox()
    if bounds is None:
        raise ValueError("Resampling produced an empty frame")
    resized = resized.crop(bounds)
    if resized.width > 60 or resized.height > 122:
        raise ValueError(f"Prepared frame exceeds expected envelope: {resized.size}")
    canvas = Image.new("RGBA", (WIDTH, HEIGHT), (0, 0, 0, 0))
    x = (WIDTH - resized.width) // 2
    y = BASELINE - resized.height
    canvas.paste(resized, (x, y))
    pixels = bytearray(canvas.tobytes())
    for offset in range(0, len(pixels), 4):
        if pixels[offset + 3] == 0:
            pixels[offset:offset + 3] = b"\0\0\0"
    return Image.frombytes("RGBA", canvas.size, bytes(pixels))


def encode_frame(image: Image.Image) -> bytes:
    pixels = image.tobytes()
    encoded = bytearray()
    position = 0
    while position < len(pixels):
        color = pixels[position:position + 4]
        count = 1
        while (count < 65535 and position + count * 4 < len(pixels)
               and pixels[position + count * 4:position + (count + 1) * 4] == color):
            count += 1
        encoded.extend(struct.pack("<H", count))
        encoded.extend(color)
        position += count * 4
    return bytes(encoded)


def verify_frame(encoded: bytes, expected: Image.Image) -> None:
    decoded = bytearray()
    if len(encoded) % 6:
        raise ValueError("RLE packet must contain exactly 6 bytes")
    for offset in range(0, len(encoded), 6):
        count = struct.unpack_from("<H", encoded, offset)[0]
        if count == 0:
            raise ValueError("Zero-length RLE run")
        decoded.extend(encoded[offset + 2:offset + 6] * count)
    if bytes(decoded) != expected.tobytes():
        raise ValueError("RLE round-trip mismatch")


def write_header(path: Path, packed: bytes, offsets: list[int]) -> None:
    lines = ["// Generated by tools/build_character_sheets.py. Do not edit.",
             "// Packet layout: countLE16, red, green, blue, alpha.",
             "// Atlas order: variant * Frames + (18 walk frames, then 25 jump frames).",
             "#pragma once", "#include <cstdint>", "",
             "namespace mario::sheet_data {",
             f"inline constexpr unsigned Frames = {FRAME_COUNT};",
             f"inline constexpr unsigned Variants = {len(VARIANTS)};",
             "inline constexpr unsigned char Packed[] = {"]
    for offset in range(0, len(packed), 36):
        lines.append("    " + ",".join(str(value) for value in packed[offset:offset + 36]) + ",")
    lines.extend(["};", "inline constexpr std::uint32_t Offsets[Variants * Frames + 1] = {"])
    for offset in range(0, len(offsets), 10):
        lines.append("    " + ",".join(str(value) for value in offsets[offset:offset + 10]) + ",")
    lines.extend(["};", "} // namespace mario::sheet_data", ""])
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def contact_sheet(frames: list[Image.Image], title: str, source_start: int,
                  columns: int = 6) -> Image.Image:
    factor, cell_width, cell_height = 2, 140, 280
    rows = (len(frames) + columns - 1) // columns
    preview = Image.new("RGB", (columns * cell_width, 32 + rows * cell_height), (25, 30, 42))
    draw = ImageDraw.Draw(preview)
    draw.text((10, 9), title + " | exact 64x128 atlas enlarged 2x", fill=(240, 244, 252))
    for index, frame in enumerate(frames):
        cell_x = (index % columns) * cell_width
        cell_y = 32 + (index // columns) * cell_height
        draw.text((cell_x + 6, cell_y + 2), f"frame {source_start + index}", fill=(239, 243, 251))
        background = Image.new("RGBA", (WIDTH, HEIGHT), (170, 176, 188, 255))
        bgdraw = ImageDraw.Draw(background)
        for y in range(0, HEIGHT, 8):
            for x in range(0, WIDTH, 8):
                if ((x // 8) + (y // 8)) % 2:
                    bgdraw.rectangle((x, y, x + 7, y + 7), fill=(204, 210, 220, 255))
        background.alpha_composite(frame)
        rendered = background.convert("RGB").resize((WIDTH * factor, HEIGHT * factor),
                                                       Image.Resampling.NEAREST)
        preview.paste(rendered, (cell_x + 6, cell_y + 18))
    return preview


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--walk", type=Path)
    parser.add_argument("--jump", type=Path)
    args = parser.parse_args()
    project = args.project.resolve()
    assets = project / "assets" / "character-sheets"
    generated = project / "generated"
    docs = project / "docs" / "sheet-character"
    for directory in (assets, generated, docs):
        directory.mkdir(parents=True, exist_ok=True)

    sources = []
    for kind, given, filename in (("walk", args.walk, "mario-walk-trimmed.png"),
                                  ("jump", args.jump, "mario-jump.png")):
        destination = assets / f"{kind}.png"
        source = given if given is not None else (
            destination if destination.is_file() else Path.home() / "Downloads" / filename)
        source = source.resolve()
        if not source.is_file():
            raise FileNotFoundError(source)
        original_sha = sha256(source)
        if source != destination.resolve():
            shutil.copyfile(source, destination)
        if sha256(destination) != original_sha:
            raise ValueError("Original asset copy changed source bytes")
        sources.append(destination)

    sheets = (read_sheet(sources[0], 5, 4, 18), read_sheet(sources[1], 5, 5, 25))
    packed = bytearray()
    offsets = [0]
    prepared = []
    records = []
    for variant_index, variant in enumerate(VARIANTS):
        variant_frames = []
        frame_index = 0
        for sheet_index, sheet in enumerate(sheets):
            for frame in sheet["frames"]:
                image = prepare_frame(frame, sheet["scales"][variant_index])
                bounds = image.getchannel("A").getbbox()
                if bounds is None or bounds[3] != BASELINE:
                    raise ValueError("Every frame must have the same bottom anchor")
                if variant == "small" and bounds[1] < 64:
                    raise ValueError("Small frame escaped the bottom 64 rows")
                if variant in ("crouch", "growth") and bounds[1] < 32:
                    raise ValueError("Short form escaped the bottom 96 rows")
                encoded = encode_frame(image)
                verify_frame(encoded, image)
                packed.extend(encoded)
                offsets.append(len(packed))
                records.append({
                    "variant": variant, "variant_index": variant_index,
                    "frame_index": frame_index,
                    "packed_index": variant_index * FRAME_COUNT + frame_index,
                    "source": "walk" if sheet_index == 0 else "jump",
                    "source_frame_index": frame["source_index"],
                    "source_alpha_bounds": list(frame["bounds"]),
                    "prepared_alpha_bounds": list(bounds),
                    "fixed_scale": sheet["scales"][variant_index],
                    "rgba_sha256": hashlib.sha256(image.tobytes()).hexdigest(),
                    "rle_bytes": len(encoded),
                    "rle_offset": offsets[-2],
                })
                variant_frames.append(image)
                frame_index += 1
        if frame_index != FRAME_COUNT:
            raise ValueError("Wrong frame count")
        prepared.append(variant_frames)
        contact_sheet(variant_frames[:18], f"Walk | {variant}", 0).save(docs / f"walk-{variant}.png")
        contact_sheet(variant_frames[18:], f"Jump | {variant}", 0, 5).save(docs / f"jump-{variant}.png")

    header = generated / "character_sheets.h"
    write_header(header, bytes(packed), offsets)
    manifest = {
        "schema": 1, "generator": "tools/build_character_sheets.py",
        "pillow_version": PILLOW_VERSION,
        "frames": FRAME_COUNT, "variants": list(VARIANTS),
        "variant_count": len(VARIANTS), "prepared_frames": FRAME_COUNT * len(VARIANTS),
        "atlas_size": [WIDTH, HEIGHT], "baseline_exclusive": BASELINE,
        "source_background": "Existing PNG alpha preserved; no color keying",
        "resampling": "Lanczos on premultiplied RGBa, converted to straight RGBA",
        "alignment": "Alpha crop; fixed per-sheet scale; horizontal bounds center; bottom row 126",
        "frame_order": "18 row-major walk frames, then 25 row-major jump frames",
        "index_order": "variant_index * 43 + frame_index",
        "rle_packet": "6 bytes: countLE16,r,g,b,a; offsets measured in bytes",
        "packed_bytes": len(packed),
        "decoded_bytes": FRAME_COUNT * len(VARIANTS) * WIDTH * HEIGHT * 4,
        "rle_round_trip_verified": True,
        "sources": [{
            "kind": "walk" if index == 0 else "jump",
            "path": sheet["path"].relative_to(project).as_posix(),
            "sha256": sha256(sheet["path"]),
            "bytes": sheet["path"].stat().st_size,
            "size": list(sheet["size"]), "grid": [sheet["columns"], sheet["rows"]],
            "cell_size": [256, 256], "retained_frames": len(sheet["frames"]),
            "empty_trailing_cells": sheet["empty"],
            "maximum_alpha_bounds_size": list(sheet["maximum_bounds_size"]),
            "fixed_scales": dict(zip(VARIANTS, sheet["scales"])),
        } for index, sheet in enumerate(sheets)],
        "generated_header": {"path": header.relative_to(project).as_posix(),
                             "bytes": header.stat().st_size, "sha256": sha256(header)},
        "frames_detail": records,
    }
    manifest_path = docs / "assets.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                             encoding="utf-8", newline="\n")
    print(json.dumps({"frames": FRAME_COUNT, "variants": len(VARIANTS),
                      "prepared_frames": len(records), "packed_bytes": len(packed),
                      "header_bytes": header.stat().st_size,
                      "header_sha256": sha256(header),
                      "manifest": str(manifest_path),
                      "sources": [{"kind": source["kind"], "sha256": source["sha256"]}
                                  for source in manifest["sources"]]}, indent=2))


if __name__ == "__main__":
    main()
