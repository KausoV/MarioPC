"""Pack transparent ImageGen paintings into standalone scenery resources."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ELDERWOOD = {"stump": (216, 592), "branch": (360, 180), "junction": (380, 560)}

FOREST_PROPS = {
    "slate": (152, 152), "active_seal": (128, 128), "spent_seal": (128, 128),
    "bridge": (448, 144), "crystal": (90, 128), "fern": (152, 126),
    "fungi": (132, 128), "geode": (152, 128), "kelp": (120, 148), "urn": (132, 128),
}

HIGHLANDS = {
    "ridge": (940, 380), "foothill": (880, 320),
    "spruce": (260, 460), "pine": (300, 450), "wayside_lantern": (150, 238),
    "fieldstone_veined": (160, 160), "fieldstone_layered": (160, 160),
    "fieldstone": (160, 160), "subsoil": (416, 416), "turf": (540, 150),
    "moon": (224, 224), "cloud": (448, 190), "cirrus": (380, 157), "stratus": (480, 150),
}

LANDMARKS = {"watchhouse": (384, 384), "gatehouse": (384, 720),
             "waypost": (80, 704), "signal_lamp": (48, 72)}

def embed_chapter_poster():
    from io import BytesIO
    source = ROOT / "assets" / "iskra" / "landmarks" / "chapter.png"
    with Image.open(source) as image:
        image = image.convert("RGB")
        image.thumbnail((1600, 900), Image.Resampling.LANCZOS)
        encoded = BytesIO()
        image.save(encoded, "PNG", optimize=True)
    raw = encoded.getvalue()
    lines = ["// Generated by tools/embed_iskra_paintings.py.", "#pragma once",
             "inline constexpr unsigned char IskraChapterPoster[] = {"]
    lines.extend("    " + ",".join(map(str, raw[i:i+32])) + "," for i in range(0, len(raw), 32))
    (ROOT / "generated" / "iskra_chapter_poster.h").write_text(
        "\n".join(lines + ["};", ""]), encoding="ascii", newline="\n")

def embed(folder, namespace, sizes, opaque=()):
    source = ROOT / "assets" / "iskra" / folder
    lines = [
        "// Generated by tools/embed_iskra_paintings.py. RGBA bytes run from high to low.",
        "#pragma once", "#include <cstdint>", f"namespace iskra::{namespace} {{",
        "struct Image { int width, height; const std::uint32_t* rgba; };",
    ]
    for name, limit in sizes.items():
        with Image.open(source / f"{name}.png") as im:
            rgba = im.convert("RGBA")
        alpha = rgba.getchannel("A")
        if name in opaque:
            if alpha.getextrema() != (255, 255):
                raise ValueError(f"Material texture must cover its entire tile: {name}")
        else:
            if alpha.getextrema()[0] != 0 or alpha.getextrema()[1] < 128:
                raise ValueError(f"Missing cutout transparency in {name}")
            threshold = 3 if name in ("cloud", "cirrus", "stratus") else 12
            bounds = alpha.point(lambda value: 255 if value >= threshold else 0).getbbox()
            rgba = rgba.crop(bounds)
        rgba.thumbnail(limit, Image.Resampling.LANCZOS)
        lines.append(f"inline constexpr std::uint32_t {name}Pixels[] = {{")
        raw = rgba.tobytes()
        for offset in range(0, len(raw), 64):
            group = raw[offset:offset+64]
            words = [f"0x{group[i:i+4].hex()}u" if group[i+3] else "0u" for i in range(0,len(group),4)]
            lines.append("    " + ",".join(words) + ",")
        lines += ["};", f"inline constexpr Image {name} = {{{rgba.width}, {rgba.height}, {name}Pixels}};"]
        print(f"{name}: {rgba.width} x {rgba.height}")
    lines += [f"}} // namespace iskra::{namespace}", ""]
    (ROOT / "generated" / f"iskra_{folder}.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")

if __name__ == "__main__":
    embed("elderwood", "elderwood", ELDERWOOD)
    embed("forest_props", "props", FOREST_PROPS)
    embed("highlands", "highlands", HIGHLANDS, opaque=("subsoil",))
    embed("landmarks", "landmarks", LANDMARKS)
    embed_chapter_poster()
