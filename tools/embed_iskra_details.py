"""Encode the selected CC0 Pixel Art Atlas sprites into the offline scenery renderer."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "assets" / "iskra" / "atlas"


def main():
    entries = json.loads((ART / "manifest.json").read_text(encoding="utf-8"))["sprites"]
    with Image.open(ART / "sprites.png") as source:
        sheet = source.convert("RGBA")
    if sheet.size != (16 * len(entries), 16):
        raise ValueError("The source strip must contain one 16 x 16 cell per manifest entry.")
    names = [entry["sprite"] for entry in entries]
    if not all(name.isascii() and name.isidentifier() for name in names) or len(names) != len(set(names)):
        raise ValueError("Sprite identifiers must be unique ASCII identifiers.")
    lines = [
        "// Generated by tools/embed_iskra_details.py from assets/iskra/atlas/sprites.png.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace iskra::detail {",
        "enum class Sprite { " + ", ".join(names) + ", Count };",
        "inline constexpr std::uint32_t rgba[static_cast<unsigned>(Sprite::Count)][256] = {",
    ]
    for i, name in enumerate(names):
        tile = sheet.crop((16 * i, 0, 16 * i + 16, 16))
        if not tile.getbbox():
            raise ValueError(f"Empty tile: {name}")
        lines.append("    { // " + name)
        for y in range(16):
            row = []
            for x in range(16):
                r, g, b, a = tile.getpixel((x, y))
                row.append(f"0x{r:02x}{g:02x}{b:02x}{a:02x}" if a else "0u")
            lines.append("        " + ", ".join(row) + ",")
        lines.append("    },")
    lines.extend(["};", "} // namespace iskra::detail", ""])
    (ROOT / "generated" / "iskra_detail_atlas.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
